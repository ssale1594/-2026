-- ============================================================
-- 1. حرج وسابق لليلة: sellers.active_listings_count قابل للتعديل المباشر
-- ============================================================
-- لم يكن ضمن قائمة الأعمدة المحجوبة بالهجرة 53 (فات إدراجه بالقائمة الأصلية).
-- أي بائع كان يقدر ينفّذ UPDATE sellers SET active_listings_count = 0
-- ويتجاوز حد الفريميوم بالكامل — يبطل can_create_listing() كليًا. هذا
-- العدّاد يُدار حصرًا بـtrigger (update_seller_listing_count)، ما له داعي
-- يكون قابلاً للكتابة المباشرة من العميل إطلاقًا.

revoke update (active_listings_count) on sellers from authenticated;

-- ============================================================
-- 2. من الليلة: أعمدة الموقع الجديدة بهجرة 55 بلا صلاحية UPDATE إطلاقًا
-- ============================================================
-- latitude/longitude/phone/address_note/neighborhood_id أُضيفت بـALTER
-- TABLE ADD COLUMN لجدول عليه فعلاً صلاحيات أعمدة مقيّدة من الهجرة 53 —
-- عمود جديد بجدول كذا لا يرث صلاحية UPDATE تلقائيًا (يختلف عن ALTER DEFAULT
-- PRIVILEGES اللي يُطبَّق على الجداول الجديدة فقط، لا الأعمدة الجديدة بجدول
-- موجود). النتيجة: /dashboard/location كانت تفشل بـ42501 عند أي محاولة
-- حفظ فعلية — لم تُكتشف قبل هذي المراجعة لأن الاختبار السابق كان بصلاحيات
-- service_role (تتجاوز RLS/column grants) لا بجلسة بائع حقيقية.

grant update (latitude, longitude, phone, address_note, neighborhood_id)
  on sellers to authenticated;

-- ============================================================
-- 3. حرج وسابق لليلة: سياسة تحديث vouches تحوي تناقض منطقي (tautology)
-- ============================================================
-- سياسة "voucher updates own within 30d" كتبت (seller_id = seller_id) و
-- (voucher_id = voucher_id) بقصد تثبيت هذين العمودين على قيمتهما القديمة —
-- لكن WITH CHECK يرى الصف الجديد فقط (لا القديم)، فمقارنة عمود بنفسه تتحقق
-- دائمًا بغض النظر عن القيمة الجديدة. النتيجة الفعلية: أي مستخدم زكّى بائعًا
-- يقدر خلال 30 يوم من التزكية يعيد توجيهها لبائع مختلف تمامًا (ينتحل تزكية
-- بائع ما استحقها)، أو يغيّر voucher_id لينتحل هوية مُزكٍّ آخر.
--
-- الحل: نفس نمط الهجرة 53 — حجب seller_id/voucher_id/id/created_at على
-- مستوى العمود، يبقى note/comment/relation/updated_at قابلة للتعديل فقط.

revoke update on vouches from authenticated;
grant update (note, comment, relation, updated_at) on vouches to authenticated;
